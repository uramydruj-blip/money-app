  function findDigitAmount(t) {
    const re = /(\d{1,3}(?:[ \u00a0\u202f]\d{3})+|\d+)(?:[.,](\d{1,2}))?(?:\s*(тисяч[а-яіїєґ]*|тысяч[а-я]*|тис\.?|тыс\.?|k|к)(?![a-zа-яіїєґ]))?/iu;
    const m = re.exec(t);
    if (!m) return null;
    let v = parseFloat(m[1].replace(/[ \u00a0\u202f]/g, '') + (m[2] ? '.' + m[2] : ''));
    if (m[3]) v *= 1000;
    return { value: v, start: m.index, end: m.index + m[0].length };
  }

