  /**
   * parse('витратив 50 на автобус') -> {type:'expense', amount:50, category:'transport', note:'Автобус', ok:true}
   */
  function parse(input) {
    const raw = String(input || '');
    let t = normalize(raw);
    let signHint = null;
    if (/^\+/.test(t)) signHint = 'income';
    else if (/^-\s*\d/.test(t)) signHint = 'expense';

    let amount = null;
    const dm = findDigitAmount(t);
    let rest = t;
    if (dm) { amount = dm.value; rest = (t.slice(0, dm.start) + ' ' + t.slice(dm.end)); }

    let tokens = rest.split(/[^a-zа-яіїєґ0-9+\-]+/iu).filter(Boolean).map(x => x.replace(/^[-+]+|[-+]+$/g, '')).filter(Boolean);

    if (amount == null) {
      const wm = findWordAmount(tokens);
      if (wm) { amount = wm.value; tokens = tokens.filter((_, i) => !wm.idx.includes(i)); }
    }

    const currency = detectCurrency(t, tokens);
    tokens = tokens.filter(x => !isCurrencyWord(x));
    const cat = detectCategory(tokens);
    const hasExpense = tokens.some(x => matchWord(x, EXPENSE_STRONG));
    const hasIncome = tokens.some(x => matchWord(x, INCOME_STRONG));
    const hasWeakIncome = tokens.some(x => matchWord(x, INCOME_WEAK));

    let type;
    const fromClient = tokens.some(x => matchWord(x, CLIENT_WORDS));
    if (signHint) type = signHint;
    else if (fromClient) type = 'income';
    else if (hasExpense) type = 'expense';
    else if (hasIncome) type = 'income';
    else if (cat) type = 'expense';
    else if (hasWeakIncome) type = 'income';
    else type = 'expense';

    const noteTokens = tokens.filter(x => !STOP.has(x) && !matchWord(x, COMMAND_WORDS) && !/^\d+$/.test(x) && !(x in NUM_WORDS));
    // для доходу прибираємо "баланс/поповнення" з примітки
    const note = cap(noteTokens.filter(x => type === 'expense' || !matchWord(x, ['баланс', 'поповн', 'пополн'])).join(' '));

    if (amount != null) amount = Math.round(amount * 100) / 100;
    return {
      ok: amount != null && amount > 0,
      type,
      amount: amount || 0,
      currency,
      category: type === 'expense' ? (cat ? cat.id : 'other') : null,
      source: type === 'income' ? detectSource(tokens) : null,
      note,
      raw,
    };
  }

