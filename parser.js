  function findWordAmount(tokens) {
    let i = 0;
    while (i < tokens.length) {
      const w = tokens[i];
      if (w in NUM_WORDS || HALF_WORDS.has(w) || (isThousand(w) && w.length > 1 && /^(тисяч|тысяч|косар)/.test(w))) {
        let total = 0, cur = 0, j = i, used = [];
        let hadAny = false;
        while (j < tokens.length) {
          const x = tokens[j];
          if (x in NUM_WORDS) { cur += NUM_WORDS[x]; used.push(j); hadAny = true; }
          else if (HALF_WORDS.has(x)) { cur += 1.5; used.push(j); hadAny = true; }
          else if (isThousand(x) && (hadAny || /^(тисяч|тысяч|косар)/.test(x))) { total += (cur || 1) * 1000; cur = 0; used.push(j); hadAny = true; }
          else break;
          j++;
        }
        const value = total + cur;
        if (hadAny && value > 0) return { value, idx: used };
        i = j + 1;
      } else i++;
    }
    return null;
  }

