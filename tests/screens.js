const { chromium } = require('/tmp/mapw/node_modules/playwright-core');
const exe = process.env.HOME + '/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome';
const URL = process.env.APP_URL || 'http://127.0.0.1:8731/index.html';
(async () => {
  const browser = await chromium.launch({ executablePath: exe });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: 'uk-UA' });
  const page = await ctx.newPage();
  const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => m.type() === 'error' && errs.push(m.text()));
  await page.goto(URL + '?demo=1'); await page.waitForTimeout(2600);
  await page.screenshot({ path: 'screens/1-main-v2.png' });
  await page.click('#btn-expense'); await page.waitForTimeout(400);
  await page.fill('#tx-amount', '240'); await page.click('#tx-cats [data-c="transport"]'); await page.fill('#tx-note', 'Таксі додому');
  await page.evaluate(() => document.activeElement.blur()); await page.waitForTimeout(300);
  await page.screenshot({ path: 'screens/2-add-expense.png' });
  await page.click('#scrim', { position: { x: 200, y: 40 } }); await page.waitForTimeout(400);
  await page.click('[data-go="history"]'); await page.waitForTimeout(900);
  await page.screenshot({ path: 'screens/3-history.png' });
  await page.screenshot({ path: 'screens/3b-history-full.png', fullPage: true });
  await page.click('#scr-history [data-back]'); await page.waitForTimeout(400);
  await page.click('#btn-mic'); await page.waitForTimeout(400);
  await page.fill('#voice-text', 'витратив 50 на автобус'); await page.press('#voice-text', 'Enter'); await page.waitForTimeout(500);
  await page.screenshot({ path: 'screens/4-voice.png' });
  await page.click('#cf-cancel'); await page.waitForTimeout(200);
  await page.evaluate(() => { document.querySelector('#sheet-voice').classList.add('listening'); document.querySelector('#voice-status').textContent = 'Слухаю… (українська)'; document.querySelector('#voice-transcript').innerHTML = 'плюс 2000 <span class="interim">зарплата</span>'; document.querySelector('#voice-text').value=''; });
  await page.waitForTimeout(700);
  await page.screenshot({ path: 'screens/4b-voice-listening.png' });
  console.log('errors:', errs);
  await browser.close();
})();
